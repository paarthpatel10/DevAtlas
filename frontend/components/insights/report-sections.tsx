import type { ReactNode } from "react";

import { CitationList, modelLabel } from "@/components/insights/citation-list";
import { MoreIdeas } from "@/components/insights/more-ideas";
import type { Citation, InsightsOut } from "@/lib/types";

const NOT_ESTABLISHED = "Not established from the README.";

function Section({ title, children }: { title: string; children: ReactNode }) {
  return (
    <section className="border-t border-rule pt-5">
      <h2 className="text-sm font-semibold">{title}</h2>
      <div className="mt-2 space-y-2 text-sm">{children}</div>
    </section>
  );
}

function Missing() {
  return <p className="italic text-muted">{NOT_ESTABLISHED}</p>;
}

function CitedList({ items }: { items: { text: string; citations: Citation[] }[] }) {
  if (items.length === 0) return <Missing />;
  return (
    <ul className="space-y-2">
      {items.map((item) => (
        <li key={item.text}>
          {item.text}
          <CitationList citations={item.citations} />
        </li>
      ))}
    </ul>
  );
}

export function ReportSections({
  insights,
  readmeUrl,
  owner,
  name,
}: {
  insights: InsightsOut;
  readmeUrl: string | null;
  owner?: string;
  name?: string;
}) {
  const { report } = insights;
  const tech = report.technical;
  const named = (items: { name: string; citations: Citation[] }[]) =>
    items.map((i) => ({ text: i.name, citations: i.citations }));

  return (
    <div className="space-y-6">
      <div className="space-y-2">
        {insights.generated ? (
          <p className="text-xs text-muted">{modelLabel(insights.model_name, insights.generated_at)}</p>
        ) : (
          <p className="rounded border border-rule bg-surface px-3 py-2 text-xs text-muted">
            No AI report yet for this repository: showing the summary from its GitHub description
            and README. AI reports are generated by a background job.
          </p>
        )}
        {insights.stale && (
          <p className="rounded border border-amber/40 bg-amber-soft px-3 py-2 text-xs text-amber">
            The README has changed since this report was generated; some details may be out of date.
          </p>
        )}
      </div>

      <Section title="Overview">
        {report.what_is_it ? (
          <>
            <p className="max-w-prose">{report.what_is_it.explanation}</p>
            <CitationList citations={report.what_is_it.citations} />
          </>
        ) : (
          <Missing />
        )}
      </Section>

      <Section title="Problem it solves">
        {report.problem_solved ? <CitedList items={[report.problem_solved]} /> : <Missing />}
      </Section>

      <Section title="Why it's worth discovering">
        {insights.why_trending.length > 0 && (
          <div>
            <h3 className="text-xs font-semibold text-muted">Measured signals</h3>
            <ul className="mt-1 list-disc space-y-0.5 pl-4">
              {insights.why_trending.map((line) => (
                <li key={line}>{line}</li>
              ))}
            </ul>
          </div>
        )}
        <h3 className="text-xs font-semibold text-muted">What makes it notable</h3>
        <CitedList items={report.why_interesting.map((p) => ({ text: p.point, citations: p.citations }))} />
      </Section>

      <Section title="Who should care">
        {report.who_should_care.length === 0 ? (
          <Missing />
        ) : (
          <ul className="space-y-2">
            {report.who_should_care.map((a) => (
              <li key={a.audience}>
                <span className="font-medium">{a.audience}:</span> {a.reason}
                <CitationList citations={a.citations} />
              </li>
            ))}
          </ul>
        )}
      </Section>

      <Section title="Core capabilities">
        <CitedList items={named(tech.capabilities)} />
      </Section>

      <Section title="Practical use cases">
        <CitedList items={report.use_cases} />
      </Section>

      <Section title="What you can build with it">
        {report.build_ideas.length === 0 ? (
          <p className="italic text-muted">No project ideas yet.</p>
        ) : (
          <ul className="space-y-3">
            {report.build_ideas.map((idea) => (
              <li key={idea.title}>
                <p className="font-medium">{idea.title}</p>
                <p>{idea.description}</p>
                <p className="text-muted">
                  <span className="text-ink">How it is used:</span> {idea.how_it_is_used}
                </p>
                {idea.complementary_tech.length > 0 && (
                  <p className="text-xs text-muted">
                    Pairs well with (suggestion): {idea.complementary_tech.join(", ")}
                  </p>
                )}
                <CitationList citations={idea.citations} />
              </li>
            ))}
          </ul>
        )}
        {owner && name && <MoreIdeas owner={owner} name={name} />}
      </Section>

      <Section title="Technical overview">
        {tech.architecture ? <CitedList items={[tech.architecture]} /> : (
          <p className="italic text-muted">The README doesn&apos;t describe the architecture.</p>
        )}
        {tech.frameworks.length > 0 && (
          <>
            <h3 className="text-xs font-semibold text-muted">Frameworks and languages</h3>
            <CitedList items={named(tech.frameworks)} />
          </>
        )}
      </Section>

      <Section title="Dependencies and integrations">
        <h3 className="text-xs font-semibold text-muted">Integrations</h3>
        <CitedList items={named(tech.integrations)} />
        <h3 className="text-xs font-semibold text-muted">Prerequisites</h3>
        <CitedList items={tech.prerequisites} />
      </Section>

      <Section title="Getting started">
        {report.getting_started.length > 0 ? (
          <ul className="space-y-1">
            {report.getting_started.map((link) => (
              <li key={link.url}>
                <a href={link.url} target="_blank" rel="noopener noreferrer" className="text-accent hover:underline">
                  {link.label}
                </a>
              </li>
            ))}
          </ul>
        ) : (
          <p className="text-muted">
            No getting-started links were found in the indexed README.
            {readmeUrl && (
              <>
                {" "}
                <a href={readmeUrl} target="_blank" rel="noopener noreferrer" className="text-accent hover:underline">
                  Read the README on GitHub
                </a>
              </>
            )}
          </p>
        )}
      </Section>

      <Section title="Limitations and considerations">
        <CitedList items={report.limitations} />
      </Section>
    </div>
  );
}
